    <script>
    (function() {
        var overlay = document.getElementById('loginOverlay');
        var openBtn = document.getElementById('openLoginModal');
        var closeBtn = document.getElementById('closeLoginModal');

        if (openBtn) {
            openBtn.addEventListener('click', function(e) {
                e.preventDefault();
                overlay.classList.add('active');
            });
        }
        if (closeBtn) {
            closeBtn.addEventListener('click', function() {
                overlay.classList.remove('active');
            });
        }
        overlay.addEventListener('click', function(e) {
            if (e.target === overlay) overlay.classList.remove('active');
        });

        window.grinSwitchTab = function(tab) {
            document.querySelectorAll('.grin-login-tab').forEach(function(t) { t.classList.remove('active'); });
            document.querySelectorAll('.grin-auth-form').forEach(function(f) { f.classList.remove('active'); });
            if (tab === 'login') {
                document.querySelectorAll('.grin-login-tab')[0].classList.add('active');
                document.getElementById('grinLoginForm').classList.add('active');
            } else {
                document.querySelectorAll('.grin-login-tab')[1].classList.add('active');
                document.getElementById('grinSignupForm').classList.add('active');
            }
        };

        function grinHandleForm(formId) {
            var form = document.getElementById(formId);
            form.addEventListener('submit', function(e) {
                e.preventDefault();
                var data = new FormData(form);
                var msgEl = document.getElementById('grinLoginMsg');
                fetch('login.php', { method: 'POST', body: data })
                    .then(function(r) { return r.json(); })
                    .then(function(res) {
                        if (res.status === 'redirect') {
                            window.location.href = res.url;
                        } else {
                            msgEl.textContent = res.message;
                            msgEl.className = res.status === 'error' ? '' : 'success';
                            msgEl.style.display = 'block';
                        }
                    })
                    .catch(function() {
                        msgEl.textContent = 'Something went wrong. Try again.';
                        msgEl.className = '';
                        msgEl.style.display = 'block';
                    });
            });
        }
        grinHandleForm('grinLoginForm');
        grinHandleForm('grinSignupForm');
    })();
    </script>
